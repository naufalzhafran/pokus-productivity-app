import { strict as assert } from 'node:assert';
import { readFile } from 'node:fs/promises';
import process from 'node:process';
import console from 'node:console';
import { URL } from 'node:url';
import PocketBase from 'pocketbase';

const endpoint = process.env.POKUS_TEST_PB_URL ?? 'http://127.0.0.1:8099';
if (!['127.0.0.1', 'localhost'].includes(new URL(endpoint).hostname)) throw new Error('Calendar tests require an isolated local PocketBase instance.');
const admin = new PocketBase(endpoint);
await admin.collection('_superusers').authWithPassword('pokus-test@example.com', 'Pokus-local-test-2026!');
await admin.collections.import(JSON.parse(await readFile('../backend/pb_schema.json', 'utf8')), false);
const projectSchema = await admin.collections.getOne('projects');
assert(projectSchema.indexes.some((index) => index.includes('idx_projects_owner_due') && /owner.*dueDate/.test(index)), 'Project deadline queries must have an owner/dueDate index.');
const stamp = Date.now();
const password = 'Pokus-calendar-test-2026!';
const user = await admin.collection('users').create({ email: `calendar-${stamp}@example.com`, password, passwordConfirm: password });
const stranger = await admin.collection('users').create({ email: `calendar-other-${stamp}@example.com`, password, passwordConfirm: password });
const pb = new PocketBase(endpoint);
pb.autoCancellation(false);
try {
  await pb.collection('users').authWithPassword(user.email, password);
  const owner = user.id;
  const foreign = await admin.collection('captures').create({ owner: stranger.id, kind: 'note', note: 'Private capture' });
  const calendarProject = await pb.collection('projects').create({ owner, title: 'Calendar deadline', dueDate: '2026-10-10', status: 'active' });
  const archivedProject = await pb.collection('projects').create({ owner, title: 'Archived calendar project', dueDate: '2026-10-10', isDone: true });
  const calendarTask = (title, values = {}) => pb.collection('tasks').create({ owner, title, ...values });
  const inherited = await calendarTask('Inherited deadline', { project: calendarProject.id });
  const override = await calendarTask('Own deadline', { project: calendarProject.id, dueDate: '2026-10-12' });
  const standalone = await calendarTask('Standalone deadline', { dueDate: '2026-10-09' });
  const unscheduled = await calendarTask('Unscheduled');
  const archivedTask = await calendarTask('Archived parent', { project: archivedProject.id, dueDate: '2026-10-09' });
  const calendarFilter = (date, openOnly = false) => `(project = '' || project.isDone = false) && ((dueDate != '' && (${date('dueDate')})) || (dueDate = '' && ((project = '' && (${date('dueDate')})) || (project != '' && (${date('project.dueDate')})))))${openOnly ? ' && isDone = false' : ''}`;
  const calendarOptions = { filter: calendarFilter((field) => `${field} >= '2026-10-01' && ${field} <= '2026-10-10'`), expand: 'project,category', fields: 'id,title,isDone,focusedSeconds,project,priority,category,dueDate,created,expand.project.title,expand.project.dueDate,expand.project.isDone,expand.category.name' };
  const visibleTasks = await pb.collection('tasks').getFullList(calendarOptions);
  assert(visibleTasks.some((item) => item.id === inherited.id && item.expand.project.dueDate === '2026-10-10'));
  assert(visibleTasks.some((item) => item.id === standalone.id && item.dueDate === '2026-10-09'));
  assert(!visibleTasks.some((item) => [override.id, unscheduled.id, archivedTask.id].includes(item.id)));
  const undatedTasks = await pb.collection('tasks').getFullList({ filter: calendarFilter((field) => `${field} = ''`, true) });
  assert(undatedTasks.some((item) => item.id === unscheduled.id));
  assert(!undatedTasks.some((item) => item.id === inherited.id));
  await pb.collection('tasks').update(override.id, { dueDate: '' });
  assert((await pb.collection('tasks').getFullList(calendarOptions)).some((item) => item.id === override.id));
  await pb.collection('tasks').update(standalone.id, { isDone: true });
  const overdueTasks = await pb.collection('tasks').getFullList({ filter: calendarFilter((field) => `${field} != '' && ${field} < '2026-10-11'`, true) });
  assert(overdueTasks.some((item) => item.id === inherited.id));
  assert(!overdueTasks.some((item) => item.id === standalone.id));
  await pb.collection('projects').delete(calendarProject.id);
  assert((await pb.collection('tasks').getFullList({ filter: calendarFilter((field) => `${field} = ''`, true) })).some((item) => item.id === inherited.id));
  await assert.rejects(pb.collection('tasks').update(inherited.id, { dueDate: 'tomorrow' }));

  const reminderAt = Date.parse('2026-10-06T09:00:00Z');
  const reminderCapture = await pb.collection('captures').create({ owner, kind: 'note', note: 'Calendar reminder', reminderAt, reminderDone: false, isProcessed: true });
  await pb.collection('captures').update(reminderCapture.id, { note: 'Edited content', preview: { title: 'Fresh preview' } });
  const reminder = await pb.collection('captures').getOne(reminderCapture.id);
  assert.equal(reminder.reminderAt, reminderAt);
  assert.equal(reminder.reminderDone, false);
  assert.equal(reminder.isProcessed, true);
  const reminderFilter = `reminderAt > 0 && reminderAt < ${Date.parse('2026-10-07T00:00:00Z')} && reminderDone = false`;
  assert((await pb.collection('captures').getFullList({ filter: reminderFilter, sort: 'reminderAt,id' })).some((item) => item.id === reminderCapture.id));
  await pb.collection('captures').update(reminderCapture.id, { reminderDone: true });
  assert(!(await pb.collection('captures').getFullList({ filter: reminderFilter })).some((item) => item.id === reminderCapture.id));
  await assert.rejects(pb.collection('captures').update(foreign.id, { reminderAt }));
  await assert.rejects(pb.collection('captures').update(reminderCapture.id, { reminderAt: -1 }));
  await assert.rejects(pb.collection('captures').update(reminderCapture.id, { reminderAt: 1000.5 }));
  await pb.collection('captures').update(reminderCapture.id, { reminderAt: 0, reminderDone: false });
  assert.equal((await pb.collection('captures').getOne(reminderCapture.id)).reminderAt, 0);
  console.log('PASS: calendar dates, inherited relation filters, overrides, unscheduled/overdue queries, archive/deletion handling, reminder metadata and owner isolation.');
} finally {
  await admin.collection('users').delete(user.id);
  await admin.collection('users').delete(stranger.id);
}
